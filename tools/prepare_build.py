"""Generate build assets: app icons (.ico/.icns) and Windows version metadata.

Everything is derived from gunshot/icon.py and gunshot.__version__, so the
version only ever needs bumping in one place.
"""

from pathlib import Path
import sys

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root))

from gunshot import __version__  # noqa: E402
from gunshot.icon import crosshair  # noqa: E402

icons = root / "packaging" / "icons"
icons.mkdir(parents=True, exist_ok=True)
big = crosshair(1024)
big.save(icons / "gunshot.ico", sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])
big.save(icons / "gunshot.icns")
big.save(icons / "gunshot.png")

parts = tuple(int(p) for p in __version__.split(".")[:3]) + (0,)
(root / "packaging" / "version_info.txt").write_text(f"""\
# Generated by tools/prepare_build.py - Windows file metadata (Properties > Details).
VSVersionInfo(
  ffi=FixedFileInfo(filevers={parts}, prodvers={parts}),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'Gunshot'),
      StringStruct('FileDescription', 'Gunshot - keyboard sound effects'),
      StringStruct('FileVersion', '{__version__}'),
      StringStruct('InternalName', 'Gunshot'),
      StringStruct('OriginalFilename', 'Gunshot.exe'),
      StringStruct('ProductName', 'Gunshot'),
      StringStruct('ProductVersion', '{__version__}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""")
print(f"build assets for v{__version__} written to {root / 'packaging'}")
